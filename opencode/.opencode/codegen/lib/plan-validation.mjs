import { REQUIREMENT_KINDS, REQUIREMENT_VERIFICATIONS, contractChecks, contractRequirements, isPureRefactor } from "./contract.mjs"

const RISKS = new Set(["low", "medium", "high"])
const RISK_RANK = { low: 0, medium: 1, high: 2 }
const ROUTES = new Set(["direct", "planned"])
const SAFE_PATH = /^(?!\/)(?!.*(?:^|\/)\.\.(?:\/|$))[A-Za-z0-9._/@*+-]+(?:\/[A-Za-z0-9._/@*+-]+)*$/

function nonEmptyString(value) {
  return typeof value === "string" && value.trim().length > 0
}

function validPathPattern(value) {
  if (!nonEmptyString(value)) return false
  if (value.endsWith("/**")) return SAFE_PATH.test(value.slice(0, -3))
  return SAFE_PATH.test(value) && !value.includes("*")
}

// `read` and `forbidden` are descriptive, so they also accept extension globs
// ("*.json", "**/*.md"); `allowed_to_modify` stays exact because it is what
// the orchestrator enforces and commits.
// A gate that asserts working-tree state (untracked files, diffs) passes in the
// builder's worktree and fails once the result is committed on the integration
// branch. Gates judge behavior and file contents only.
const GIT_STATE_COMMAND = /\bgit\s+(status|diff|ls-files|log|show)\b/
// The gate wrapper is generated by the orchestrator around the checks; a
// check that calls it would recurse.
const GATE_WRAPPER_COMMAND = /\.codegen-contract\/gate\.sh/

const EXTENSION_GLOB = /^(?:\*\*\/)?\*\.[A-Za-z0-9_.-]+$/
function validDescriptivePattern(value) {
  return validPathPattern(value) || (nonEmptyString(value) && EXTENSION_GLOB.test(value))
}

function extensionOf(pattern) {
  const match = EXTENSION_GLOB.test(pattern) ? pattern.match(/\*(\.[A-Za-z0-9_.-]+)$/) : null
  return match ? match[1] : null
}

function patternPrefix(pattern) {
  return pattern.endsWith("/**") ? pattern.slice(0, -3) : pattern
}

export function pathPatternsOverlap(left, right) {
  // An extension glob overlaps an exact path with that extension.
  for (const [glob, other] of [[left, right], [right, left]]) {
    const extension = extensionOf(glob)
    if (extension) return !other.endsWith("/**") && !extensionOf(other) && other.endsWith(extension)
  }
  const leftPrefix = patternPrefix(left)
  const rightPrefix = patternPrefix(right)
  if (!left.endsWith("/**") && !right.endsWith("/**")) return left === right
  if (left.endsWith("/**") && right.endsWith("/**")) {
    return (
      leftPrefix === rightPrefix ||
      leftPrefix.startsWith(`${rightPrefix}/`) ||
      rightPrefix.startsWith(`${leftPrefix}/`)
    )
  }
  const directory = left.endsWith("/**") ? leftPrefix : rightPrefix
  const candidate = left.endsWith("/**") ? right : left
  return candidate === directory || candidate.startsWith(`${directory}/`)
}

function phasesReachableFrom(phaseId, phasesById, memo = new Map()) {
  if (memo.has(phaseId)) return memo.get(phaseId)
  const reachable = new Set()
  memo.set(phaseId, reachable)
  for (const dependency of phasesById.get(phaseId)?.depends_on ?? []) {
    reachable.add(dependency)
    for (const ancestor of phasesReachableFrom(dependency, phasesById, memo)) {
      reachable.add(ancestor)
    }
  }
  return reachable
}

function executionWaves(phases, phasesById) {
  const remaining = new Set(phases.map((phase) => phase.phase_id))
  const completed = new Set()
  const waves = []
  while (remaining.size > 0) {
    const ready = phases
      .filter((phase) => remaining.has(phase.phase_id))
      .filter((phase) => phase.depends_on.every((dependency) => completed.has(dependency)))
      .map((phase) => phase.phase_id)
    if (ready.length === 0) return null
    waves.push(ready)
    for (const phaseId of ready) {
      remaining.delete(phaseId)
      completed.add(phaseId)
    }
  }
  return waves
}

// Requirements carry ids, a kind, and a verification mode; every automated
// requirement needs a check, and a check may only cover requirements that can
// be checked. The expected baseline of a check is never declared: it follows
// from the kinds of the requirements it covers (see contract.mjs).
export function validateRequirementsAndChecks(contract, contractId, errors) {
  if (!Array.isArray(contract?.requirements)) {
    errors.push(`${contractId}: requirements must be an array`)
    return
  }
  if (contract.requirements.length === 0) errors.push(`${contractId}: requirements cannot be empty`)
  const requirementIds = new Set()
  for (const raw of contract.requirements) {
    if (!raw || typeof raw !== "object") {
      errors.push(`${contractId}: every requirement is an object with id and statement`)
      continue
    }
    if (!nonEmptyString(raw.id)) errors.push(`${contractId}: requirement id is required`)
    else if (requirementIds.has(raw.id)) errors.push(`${contractId}: duplicate requirement id ${raw.id}`)
    else requirementIds.add(raw.id)
    if (!nonEmptyString(raw.statement)) errors.push(`${contractId}: requirement ${raw.id ?? "?"} needs a statement`)
    if (raw.kind !== undefined && !REQUIREMENT_KINDS.includes(raw.kind)) {
      errors.push(`${contractId}: requirement ${raw.id ?? "?"} kind must be change or preserve`)
    }
    if (raw.verification !== undefined && !REQUIREMENT_VERIFICATIONS.includes(raw.verification)) {
      errors.push(`${contractId}: requirement ${raw.id ?? "?"} verification must be automated or manual`)
    }
    if (raw.covers !== undefined && (!Array.isArray(raw.covers) || raw.covers.some((id) => !nonEmptyString(id)))) {
      errors.push(`${contractId}: requirement ${raw.id ?? "?"} covers must be an array of Goal ids`)
    }
  }
  const requirements = contractRequirements(contract)
  const byId = new Map(requirements.map((item) => [item.id, item]))
  if (requirements.length > 0 && !requirements.some((item) => item.verification === "automated")) {
    errors.push(`${contractId}: every requirement is manual, so nothing can gate the Builder; at least one requirement must be automated`)
  }

  const verification = contract?.verification
  if (verification?.commands !== undefined) {
    errors.push(`${contractId}: verification.commands was replaced by verification.checks, one check per requirement it covers`)
  }
  if (verification?.expected_baseline !== undefined) {
    errors.push(`${contractId}: verification.expected_baseline is not declared; it follows from the kind of the requirements each check covers`)
  }
  if (!Array.isArray(verification?.checks) || verification.checks.length === 0) {
    errors.push(`${contractId}: verification.checks cannot be empty`)
  }
  if (!Array.isArray(verification?.invariants)) {
    errors.push(`${contractId}: verification.invariants must be an array`)
  }
  const checkIds = new Set()
  const covered = new Map()
  for (const check of contractChecks(contract)) {
    const checkId = nonEmptyString(check.id) ? check.id : "?"
    if (!nonEmptyString(check.id)) errors.push(`${contractId}: check id is required`)
    else if (checkIds.has(check.id)) errors.push(`${contractId}: duplicate check id ${check.id}`)
    else checkIds.add(check.id)
    if (!nonEmptyString(check.command)) errors.push(`${contractId}: check ${checkId} needs a command`)
    else {
      if (GIT_STATE_COMMAND.test(check.command)) {
        errors.push(`${contractId}: check ${checkId} must not inspect Git state (${check.command.trim().slice(0, 40)}…): the gate reruns on the integrated branch where the change is committed; scope is enforced by the orchestrator`)
      }
      if (GATE_WRAPPER_COMMAND.test(check.command)) {
        errors.push(`${contractId}: check ${checkId} must not call .codegen-contract/gate.sh; the orchestrator generates that wrapper around the checks`)
      }
    }
    if (!Array.isArray(check.covers) || check.covers.length === 0) {
      errors.push(`${contractId}: check ${checkId} must cover at least one requirement id`)
      continue
    }
    for (const id of check.covers) {
      const requirement = byId.get(id)
      if (!requirement) {
        errors.push(`${contractId}: check ${checkId} covers unknown requirement ${id}`)
        continue
      }
      if (requirement.verification === "manual") {
        errors.push(`${contractId}: manual requirement ${id} is covered by check ${checkId}; a requirement a check can verify is automated`)
      }
      if (!covered.has(id)) covered.set(id, [])
      covered.get(id).push(checkId)
    }
  }
  for (const requirement of requirements) {
    if (requirement.verification === "automated" && !covered.has(requirement.id)) {
      errors.push(`${contractId}: requirement ${requirement.id} has no check; every automated requirement needs one that proves it`)
    }
  }
}

// Maps each Goal requirement and acceptance criterion to the contract
// requirements that claim it. Statuses describe what the plan promises, not
// what happened: "covered" needs an automated claim, "manual-only" means only
// manual claims, "pending-human" is a Goal criterion nobody can automate.
export function planCoverage(plan, goal) {
  const contracts = (plan?.phases ?? []).flatMap((phase) =>
    (phase?.contracts ?? []).map((contract) => ({
      contract_id: contract?.contract_id ?? "?",
      requirements: contractRequirements(contract),
      pure_refactor: isPureRefactor(contract),
    })),
  )
  const claims = new Map()
  const unknown = []
  const goalIds = new Set([
    ...(goal?.requirements ?? []).map((item) => item.id),
    ...(goal?.acceptance_criteria ?? []).map((item) => item.id),
  ])
  for (const contract of contracts) {
    for (const requirement of contract.requirements) {
      for (const goalId of requirement.covers) {
        const claim = {
          contract_id: contract.contract_id,
          requirement_id: requirement.id,
          kind: requirement.kind,
          verification: requirement.verification,
        }
        if (!goalIds.has(goalId)) {
          unknown.push({ ...claim, goal_id: goalId })
          continue
        }
        if (!claims.has(goalId)) claims.set(goalId, [])
        claims.get(goalId).push(claim)
      }
    }
  }
  function status(list, { automatable }) {
    if (!automatable) return "pending-human"
    if (list.some((claim) => claim.verification === "automated")) return "covered"
    if (list.length > 0) return "manual-only"
    return "uncovered"
  }
  const requirements = (goal?.requirements ?? []).map((item) => {
    const list = claims.get(item.id) ?? []
    return { id: item.id, priority: item.priority, statement: item.statement, claims: list, status: status(list, { automatable: true }) }
  })
  const acceptanceCriteria = (goal?.acceptance_criteria ?? []).map((item) => {
    const list = claims.get(item.id) ?? []
    return {
      id: item.id,
      verification_type: item.verification_type,
      criterion: item.criterion,
      claims: list,
      status: status(list, { automatable: item.verification_type === "automated" }),
    }
  })
  const manualRequirements = contracts.flatMap((contract) =>
    contract.requirements
      .filter((requirement) => requirement.verification === "manual")
      .map((requirement) => ({ contract_id: contract.contract_id, requirement_id: requirement.id, statement: requirement.statement })),
  )
  return {
    requirements,
    acceptance_criteria: acceptanceCriteria,
    unknown_goal_ids: unknown,
    pure_refactor_contracts: contracts.filter((contract) => contract.pure_refactor).map((contract) => contract.contract_id),
    manual_contract_requirements: manualRequirements,
  }
}

// Coverage errors block the plan: a must requirement nobody claims, an
// automated criterion without an automated claim, a claim on an id the Goal
// does not define. Everything else is reported through planCoverage.
function coverageErrors(coverage, { partial = false } = {}) {
  const errors = []
  for (const claim of coverage.unknown_goal_ids) {
    errors.push(`${claim.contract_id}: requirement ${claim.requirement_id} covers unknown Goal id ${claim.goal_id}`)
  }
  if (partial) return errors
  for (const requirement of coverage.requirements) {
    if (requirement.priority === "must" && requirement.status === "uncovered") {
      errors.push(`Goal requirement ${requirement.id} (must) is not covered by any contract requirement: "${requirement.statement}"`)
    }
  }
  for (const criterion of coverage.acceptance_criteria) {
    if (criterion.verification_type === "automated" && criterion.status !== "covered") {
      errors.push(`Goal acceptance criterion ${criterion.id} (automated) is not covered by any automated contract requirement: "${criterion.criterion}"`)
    }
  }
  return errors
}

// Risk floors: a glob over the paths a contract may modify implies a minimum
// risk. `*` stays within one segment, `**` crosses segments.
function globToRegExp(pattern) {
  let source = ""
  for (let index = 0; index < pattern.length; index += 1) {
    const char = pattern[index]
    if (char === "*") {
      if (pattern[index + 1] === "*") {
        const slashAfter = pattern[index + 2] === "/"
        source += slashAfter ? "(?:.*/)?" : ".*"
        index += slashAfter ? 2 : 1
      } else {
        source += "[^/]*"
      }
    } else if (/[.+?^${}()|[\]\\]/.test(char)) {
      source += `\\${char}`
    } else {
      source += char
    }
  }
  return new RegExp(`^${source}$`)
}

function fixedPrefix(pattern) {
  const star = pattern.indexOf("*")
  return star === -1 ? pattern : pattern.slice(0, star)
}

// An exact allowed path touches a floor when the glob matches it. An allowed
// dir/** touches a floor when the directory lies inside the glob (probed with
// a file below it) or the glob's fixed prefix lies inside the directory.
export function allowedPathTouches(allowed, floorPattern) {
  const regexp = globToRegExp(floorPattern)
  if (!allowed.endsWith("/**")) return regexp.test(allowed)
  const directory = allowed.slice(0, -3)
  if (regexp.test(`${directory}/probe`)) return true
  const prefix = fixedPrefix(floorPattern)
  return prefix.startsWith(`${directory}/`)
}

export function riskFloorFor(contract, riskFloors) {
  const hits = []
  for (const floor of riskFloors?.floors ?? []) {
    if (!RISKS.has(floor?.risk)) continue
    for (const allowed of contract?.allowed_to_modify ?? []) {
      const pattern = (floor.patterns ?? []).find((candidate) => allowedPathTouches(allowed, candidate))
      if (pattern) hits.push({ path: allowed, pattern, risk: floor.risk, reason: floor.reason ?? pattern })
    }
  }
  const floor = hits.reduce((highest, hit) => (RISK_RANK[hit.risk] > RISK_RANK[highest] ? hit.risk : highest), "low")
  return { floor, hits }
}

// The Goal Manager's triage (shape, risk) is a first look. Once the Planner
// names contracts and paths, the code judges again and only ever raises: a
// direct route that needs more than one contract becomes planned; a
// contract's effective risk is the highest of its declared risk and the floor
// its paths imply. Anything above the Goal's labels is a contradiction the
// user must accept at plan review. Nothing here lowers an approved label.
export function triageAssessment(plan, { goal = null, route = null, riskFloors = null } = {}) {
  const contracts = (plan?.phases ?? []).flatMap((phase) => phase?.contracts ?? [])
  const goalRisk = goal?.routing?.risk ?? null
  const contradictions = []
  const assessments = contracts.map((contract) => {
    const declared = RISKS.has(contract?.risk) ? contract.risk : "low"
    const { floor, hits } = riskFloorFor(contract, riskFloors)
    const effective = RISK_RANK[floor] > RISK_RANK[declared] ? floor : declared
    if (goalRisk && RISK_RANK[declared] > RISK_RANK[goalRisk]) {
      contradictions.push({
        label: "risk",
        claimed: goalRisk,
        effective: declared,
        evidence: `${contract?.contract_id ?? "?"}: the Planner declared risk ${declared}`,
      })
    }
    if (goalRisk && RISK_RANK[floor] > RISK_RANK[goalRisk]) {
      for (const hit of hits.filter((item) => RISK_RANK[item.risk] > RISK_RANK[goalRisk])) {
        contradictions.push({
          label: "risk",
          claimed: goalRisk,
          effective: hit.risk,
          evidence: `${contract?.contract_id ?? "?"}: may modify ${hit.path}, ${hit.reason} (floor ${hit.risk})`,
        })
      }
    }
    return { contract_id: contract?.contract_id ?? "?", risk_declared: declared, risk_floor: floor, floor_reasons: hits, risk_effective: effective }
  })
  let routeEffective = ROUTES.has(route) ? route : null
  if (route === "direct" && contracts.length > 1) {
    routeEffective = "planned"
    contradictions.push({
      label: "change_shape",
      claimed: goal?.routing?.change_shape ?? "localized",
      effective: "multi-component",
      evidence: `the plan needs ${contracts.length} contracts; the direct route holds one`,
    })
  }
  const riskEffective = assessments.reduce(
    (highest, item) => (RISK_RANK[item.risk_effective] > RISK_RANK[highest] ? item.risk_effective : highest),
    goalRisk ?? "low",
  )
  return {
    route_goal: route,
    route_effective: routeEffective,
    risk_goal: goalRisk,
    risk_effective: riskEffective,
    existing_gate_goal: goal?.routing?.existing_gate ?? null,
    contradictions,
    contracts: assessments,
  }
}

// `goal`, when given, adds the coverage rules (every must requirement and
// every automated acceptance criterion accounted for) and the triage
// assessment against the Goal's labels. `route` and `riskFloors` feed the
// triage; neither rejects a plan.
// `partialCoverage` is for repair plans: they extend a plan the user already
// approved, so `covers` must still name real Goal ids but need not account
// for the whole Goal again.
export function validatePlan(plan, { workClasses = null, goal = null, route = null, riskFloors = null, partialCoverage = false } = {}) {
  const errors = []
  if (plan?.schema_version !== 1) errors.push("schema_version must be 1")
  for (const field of ["plan_id", "objective", "base_revision"]) {
    if (!nonEmptyString(plan?.[field])) errors.push(`${field} must be a non-empty string`)
  }
  if (plan?.final_verification !== undefined) {
    if (
      !Array.isArray(plan.final_verification?.commands) ||
      plan.final_verification.commands.some((command) => !nonEmptyString(command))
    ) {
      errors.push("final_verification.commands must be an array of commands")
    } else if (plan.final_verification.commands.some((command) => GIT_STATE_COMMAND.test(command))) {
      errors.push("final_verification.commands must not inspect Git state")
    }
  }
  if (!Array.isArray(plan?.phases) || plan.phases.length === 0) {
    errors.push("phases must be a non-empty array")
    return { valid: false, errors, execution_waves: [], coverage: null, triage: null }
  }

  const phasesById = new Map()
  const contractIds = new Set()
  for (const phase of plan.phases) {
    if (!nonEmptyString(phase?.phase_id)) {
      errors.push("every phase must define phase_id")
      continue
    }
    if (phasesById.has(phase.phase_id)) errors.push(`duplicate phase_id: ${phase.phase_id}`)
    phasesById.set(phase.phase_id, phase)
  }

  for (const phase of plan.phases) {
    const phaseId = phase.phase_id ?? "unknown"
    if (!nonEmptyString(phase.objective)) errors.push(`${phaseId}: objective is required`)
    if (!Array.isArray(phase.depends_on)) errors.push(`${phaseId}: depends_on must be an array`)
    for (const dependency of phase.depends_on ?? []) {
      if (!phasesById.has(dependency)) errors.push(`${phaseId}: unknown dependency ${dependency}`)
      if (dependency === phaseId) errors.push(`${phaseId}: phase cannot depend on itself`)
    }
    if (!Array.isArray(phase.contracts) || phase.contracts.length === 0) {
      errors.push(`${phaseId}: contracts must be a non-empty array`)
      continue
    }

    for (const contract of phase.contracts) {
      const contractId = contract?.contract_id ?? "unknown"
      if (!nonEmptyString(contract?.contract_id)) errors.push(`${phaseId}: contract_id is required`)
      else if (contractIds.has(contractId)) errors.push(`duplicate contract_id: ${contractId}`)
      else contractIds.add(contractId)
      if (!nonEmptyString(contract?.objective)) errors.push(`${contractId}: objective is required`)
      if (!RISKS.has(contract?.risk)) errors.push(`${contractId}: invalid risk`)
      if (!nonEmptyString(contract?.work_class)) errors.push(`${contractId}: work_class is required`)
      else if (workClasses && !workClasses.has(contract.work_class)) {
        errors.push(`${contractId}: unknown work_class ${contract.work_class}`)
      }
      for (const field of ["read", "allowed_to_modify", "forbidden", "response"]) {
        if (!Array.isArray(contract?.[field])) errors.push(`${contractId}: ${field} must be an array`)
      }
      if (contract?.allowed_to_modify?.length === 0) {
        errors.push(`${contractId}: allowed_to_modify cannot be empty`)
      }
      for (const field of ["read", "allowed_to_modify", "forbidden"]) {
        const accepts = field === "allowed_to_modify" ? validPathPattern : validDescriptivePattern
        for (const pattern of contract?.[field] ?? []) {
          if (!accepts(pattern)) {
            errors.push(
              `${contractId}: unsupported path pattern in ${field}: ${pattern} (use an exact path or dir/**${field === "allowed_to_modify" ? "" : "; *.ext is also accepted here"})`,
            )
          }
        }
      }
      for (const allowed of contract?.allowed_to_modify ?? []) {
        for (const forbidden of contract?.forbidden ?? []) {
          if (pathPatternsOverlap(allowed, forbidden)) {
            errors.push(`${contractId}: allowed path overlaps forbidden path: ${allowed}`)
          }
        }
      }
      validateRequirementsAndChecks(contract, contractId, errors)
    }
  }

  const waves = executionWaves(plan.phases, phasesById)
  if (!waves) errors.push("phase dependency graph contains a cycle")

  const reachability = new Map()
  for (const phase of plan.phases) phasesReachableFrom(phase.phase_id, phasesById, reachability)
  for (let leftIndex = 0; leftIndex < plan.phases.length; leftIndex += 1) {
    for (let rightIndex = leftIndex + 1; rightIndex < plan.phases.length; rightIndex += 1) {
      const left = plan.phases[leftIndex]
      const right = plan.phases[rightIndex]
      const ordered =
        reachability.get(left.phase_id)?.has(right.phase_id) ||
        reachability.get(right.phase_id)?.has(left.phase_id)
      if (ordered) continue
      for (const leftContract of left.contracts ?? []) {
        for (const rightContract of right.contracts ?? []) {
          for (const leftPath of leftContract.allowed_to_modify ?? []) {
            for (const rightPath of rightContract.allowed_to_modify ?? []) {
              if (pathPatternsOverlap(leftPath, rightPath)) {
                errors.push(
                  `parallel contracts ${leftContract.contract_id} and ${rightContract.contract_id} overlap at ${leftPath} / ${rightPath}`,
                )
              }
            }
          }
        }
      }
    }
  }

  for (const phase of plan.phases) {
    const contracts = phase.contracts ?? []
    for (let leftIndex = 0; leftIndex < contracts.length; leftIndex += 1) {
      for (let rightIndex = leftIndex + 1; rightIndex < contracts.length; rightIndex += 1) {
        for (const leftPath of contracts[leftIndex].allowed_to_modify ?? []) {
          for (const rightPath of contracts[rightIndex].allowed_to_modify ?? []) {
            if (pathPatternsOverlap(leftPath, rightPath)) {
              errors.push(
                `parallel contracts ${contracts[leftIndex].contract_id} and ${contracts[rightIndex].contract_id} overlap at ${leftPath} / ${rightPath}`,
              )
            }
          }
        }
      }
    }
  }

  const coverage = goal ? planCoverage(plan, goal) : null
  if (coverage) errors.push(...coverageErrors(coverage, { partial: partialCoverage }))
  const triage = goal || route ? triageAssessment(plan, { goal, route, riskFloors }) : null

  return { valid: errors.length === 0, errors, execution_waves: waves ?? [], coverage, triage }
}
